const ArrayList = std.ArrayList;

fn generateEntityComponentHolder(comptime Components: []const type) type {
    //const Base_Struct = struct {};
    //var  = []const std.builtin.Type.StructField = @typeInfo(Base_Struct).@"struct".fields;
    var struct_fields: [Components.len]std.builtin.Type.StructField = undefined;
    
    for (struct_fields[0..struct_fields.len], Components) |*struct_field, t| {
        struct_field.* = .{
            .name = @typeName(t),
            .type = ?*const t,
            .default_value_ptr = null,
            .is_comptime = false,
            .alignment = @alignOf(?*const t),
        };
    }

    return @Type(.{ .@"struct" = .{
        .layout = .auto,
        .fields = &struct_fields,
        .decls = &.{},
        .is_tuple = false,
    }});
}

fn initEntityComponentHolder(comptime Components: []const type) generateEntityComponentHolder(Components) {
    var ech: generateEntityComponentHolder(Components) = undefined;
    inline for (Components) |t| {
        @field(ech, @typeName(t)) = null;
    }
    return ech;
}

// Generates an entity type needed for GenerateECSType
pub fn generateEntityType(comptime Components: []const type) type {
    const count = Components.len;
    const ComponentHolder: type = generateEntityComponentHolder(Components);

    return struct {
        components_set: std.bit_set.StaticBitSet(count),
        linked_components: ComponentHolder,
   
        const Self = @This();

        pub fn init() generateEntityType(Components) {
            return .{
                .components_set = std.bit_set.StaticBitSet(count).initEmpty(),
                .linked_components = initEntityComponentHolder(Components),
            };
        }

        pub fn addComponent(self: *Self, index: u32, component: anytype) void {
            self.components_set.set(index);
            @field(self.linked_components, @typeName(@TypeOf(component.*))) = component;
        }

        pub fn removeComponent(self: *Self, index: u32, component: anytype) void {
            self.components_set.unset(index);
            @field(self.linked_components, @typeName(@TypeOf(component.*))) = null;
        }

        pub fn checkSet(self: *Self, index: u32) bool {
            return self.components_set.isSet(index);
        }

        pub fn removeLinkedComponent(self: *Self, component: anytype) void {
            @field(self.linked_components, @typeName(component)) = null;
        }
    };
}

pub fn printHashMap(comptime K: type, comptime V: type, map: *std.AutoHashMap(K, V)) void {
    var it = map.iterator();
    while (it.next()) |entry| {
        std.debug.print("Key: {any}, Value: {any}({p})\n", .{ entry.key_ptr.*, entry.value_ptr.*, entry.value_ptr });
    }
}

const Callback = *const fn(dt: f32, entitites: *std.ArrayList(u32)) void;

pub fn GenerateSystem(comptime Components: []const type) type {
    return struct {
        signature: std.bit_set.StaticBitSet(Components.len),
        callback: Callback,

        linked_entities: std.ArrayList(u32),
    };
}

// Generates a Component_Struct type for an ECS - used for GenerateECSType
pub fn GenerateComponentStructType(comptime Components: []const type) type {
    const Base_Struct = struct {
    };
    const fixed_fields: []const std.builtin.Type.StructField = @typeInfo(Base_Struct).@"struct".fields;

    var struct_fields: [fixed_fields.len+(Components.len*2)]std.builtin.Type.StructField = undefined;

    std.mem.copyForwards(std.builtin.Type.StructField, struct_fields[0..fixed_fields.len], fixed_fields);
    for (struct_fields[fixed_fields.len..fixed_fields.len+Components.len], Components) |*struct_field, t| {
        struct_field.* = .{
            .name = "component_"++@typeName(t),
            .type = std.AutoHashMap(u32, *const t),
            .default_value_ptr = null,
            .is_comptime = false,
            .alignment = @alignOf(std.AutoHashMap(u32, *t)),
        };
    }
    for (struct_fields[fixed_fields.len+Components.len..], Components) |*struct_field, t| {
        struct_field.* = .{
            .name = "rev_component_"++@typeName(t),
            .type = std.AutoHashMap(*const t, u32),
            .default_value_ptr = null,
            .is_comptime = false,
            .alignment = @alignOf(std.AutoHashMap(*t, u32)),
        };
    }

    return @Type(.{ .@"struct" = .{
        .layout = .auto,
        .fields = &struct_fields,
        .decls = &.{},
        .is_tuple = false,
    }});
}

fn getComponentTypeFromComponent(component: anytype) type {
    if (@typeInfo(@TypeOf(component)) != .pointer) {
        @compileError("Expected a pointer type");
    }
    return @typeInfo(@TypeOf(component)).pointer.child; 
}

// Generates a ECS based on the Component_Struct_Type generated by GenerateComponentStructType
pub fn GenerateECSType(comptime Entity_Type: type, comptime Component_Struct_Type: type, comptime Components: []const type) type {
    const ID_Manager = struct {
        next: u32 = 0,
        free: std.ArrayList(u32),

        const Self = @This();

        pub fn getNext(self: *Self) u32 {
            const last = self.free.pop();
            if (last == null) {
                self.next+=1;
                return self.next-1;
            }
            return last.?;
        }

        // Doesn't check if entity is already removed. Calling multiple times on the same entity might lead to congestion
        pub fn remove(self: *Self, entity: u32) void {
            if (entity == self.next-1) {
                self.next-=1;
                return;
            }

            self.free.append(entity) catch |err| {
                std.debug.panic("{}\n", .{err});
            };
        }
    };

    const System = GenerateSystem(Components);
    return struct {
        const Self = @This();
        
        allocator: std.mem.Allocator,

        entity_id_manager: ID_Manager,
        //component_id_manager: ID_Manager,
        entities: std.AutoHashMap(u32, *Entity_Type),
        components: Component_Struct_Type,
        
        component_index_map: std.StringHashMap(u32),

        systems_pre: []const *System,
        systems: []const *System,
        systems_post: []const *System,
        
        pub fn init(allocator: std.mem.Allocator, systems_configs: struct {pre: []const *System = &[_]*System{}, on: []const *System = &[_]*System{}, post: []const *System = &[_]*System{}}) !Self {
            var temp = std.StringHashMap(u32).init(allocator);
            const component_types = @typeInfo(Component_Struct_Type).@"struct".fields;
            inline for (component_types) |t| {
                try temp.put(t.name, temp.count());
            }

            return .{
                .allocator = allocator,
                .entity_id_manager = .{
                    .next = 0,
                    .free = std.ArrayList(u32).init(allocator),
                },
                .entities = std.AutoHashMap(u32, *Entity_Type).init(allocator),
                .components = initComponentStruct(Component_Struct_Type, Components, allocator),
                
                .component_index_map = temp,

                .systems_pre = systems_configs.pre,
                .systems = systems_configs.on,
                .systems_post = systems_configs.post,
            };
        }

        pub fn deinit(self: *Self) void {
            var entityIt = self.entities.iterator();
            while (entityIt.next()) |entity| {
                _ = self.removeEntity(entity.key_ptr.*);
            }

            self.component_index_map.deinit();

            inline for (Components) |T| {
                @field(self.components, "component_" ++ @typeName(T)).deinit();
                @field(self.components, "rev_component_" ++ @typeName(T)).deinit();
            }
        }
        
        const EntityUpdateType = enum {
            ADDED,
            REMOVED,
            COMP_REMOVED,
        };
        fn systemsRunner(self: *Self, runner: fn (*System, *Entity_Type, u32) void, entity: u32) void {
            const e = self.entities.get(entity) orelse std.debug.panic("No entity with ID {d} found\n", .{entity}); 
            for (self.systems_pre) |sys| {
                runner(sys, e, entity);
            }
            for (self.systems) |sys| {
                runner(sys, e, entity);
            }
            for (self.systems_post) |sys| {
                runner(sys, e, entity);
            }
        }          
        fn entityUpdate(self: *Self, entity: u32, comptime update_type: EntityUpdateType) void {
            switch (update_type) {
                EntityUpdateType.ADDED => {
                    self.systemsRunner(struct { fn runner(system: *System, e: *Entity_Type, en: u32)void {
                        if (system.signature.subsetOf(e.components_set)) {
                            system.linked_entities.append(en) catch |err| {
                                std.debug.panic("Failed to add entity to system: {}\n", .{err});
                            };
                            std.debug.print("Added entity {d} to system {p}\n", .{en, &system});
                        }
                    }}.runner, entity); 
                }, 
                EntityUpdateType.REMOVED => {
                    self.systemsRunner(struct { fn runner(system: *System, e: *Entity_Type, en: u32)void {
                        _ = e;
                        for (system.linked_entities.items, 0..) |v, i| {
                            if (v == en) {
                                _ = system.linked_entities.orderedRemove(i);
                                return;
                            }
                        }
                    }}.runner, entity); 
                }, 
                EntityUpdateType.COMP_REMOVED => {
                    self.systemsRunner(struct { fn runner(system: *System, e: *Entity_Type, en: u32)void {
                        for (system.linked_entities.items, 0..) |v, i| {
                            if (v == en) {
                                if (!system.signature.subsetOf(e.components_set)) {
                                    _ = system.linked_entities.orderedRemove(i);
                                    std.debug.print("Removed entity {d} from system {p}\n", .{en, &system});
                                }
                            }
                        }
                    }}.runner, entity); 
                }, 
            }
        }

        // Adds an entity, returns the id
        pub fn addEntity(self: *Self) u32 {
            const entity: *Entity_Type = self.allocator.create(Entity_Type) catch |err| {
                std.debug.panic("Could not allocate memory for entity: {}\n", .{err});
            };
            entity.* = Entity_Type.init();
            const id = self.entity_id_manager.getNext(); 
            self.entities.put(id, entity) catch |err| {
                std.debug.panic("{}\n", .{err});
            };
            printHashMap(u32, *Entity_Type, &self.entities);
            self.entityUpdate(id, EntityUpdateType.ADDED);
            return id;
        }

        // Removes an entity, returns true if removal was successful
        // Does NOT .deinit entites! Call getLinkedEntities before to deinit manually
        pub fn removeEntity(self: *Self, entity: u32) bool {
            var e = self.entities.get(entity) orelse std.debug.panic("Failed to find entity with ID {d}\n", .{entity});
            
            self.entityUpdate(entity, EntityUpdateType.REMOVED);
            
            inline for (0..Components.len, Components) |i, T| {
                const s = e.checkSet(i);
                if (s) {
                    e.removeLinkedComponent(T);
                }

            }
            
            
            const rem = self.entities.remove(entity);
            if (rem) {
                self.entity_id_manager.remove(entity);
            }
            self.allocator.destroy(e);

            return rem;
        }

        fn getComponentMapNameFromType(pointee_type: type) []const u8 {
            return "component_" ++ @typeName(pointee_type);
        }

        fn getComponentMapPointerFromName(self: *Self, comptime name: []const u8) *@TypeOf(@field(self.components, name)) {
            return &@field(self.components, name);
        }

        // Adds a component to a specified entity
        pub fn addComponent(self: *Self, entity: u32, comptime component: anytype) void {
            // Aquire correct map
            const pointee_type = getComponentTypeFromComponent(component);
            var component_map = self.getComponentMapPointerFromName(getComponentMapNameFromType(pointee_type));
            var rev_component_map = self.getComponentMapPointerFromName("rev_"++getComponentMapNameFromType(pointee_type));
           
            // Check if entity is already registered
            const t = rev_component_map.get(component);
            if (t != null) {
                std.debug.panic("Component {p} is already added\n", .{component});
            }
            const index = self.component_index_map.get("component_" ++ @typeName(pointee_type)) orelse std.debug.panic("No entry in component_index_map for {s}\n", .{@typeName(pointee_type)});
            var e = self.entities.get(entity) orelse std.debug.panic("No entity with ID {d} exists\n", .{entity});
            if (e.checkSet(index)) {
                std.debug.panic("Entity {d} already has a component of type {s} attached\n", .{entity, @typeName(pointee_type)});
            }

            // Register new component
            //const id = self.component_id_manager.getNext();
            component_map.put(entity, component) catch |err| {
                std.debug.panic("{}\n", .{err});
            };
            rev_component_map.put(component, entity) catch |err| {
                std.debug.panic("{}\n", .{err});
            };
            
            // Register component in entity
            e.addComponent(index, component);
            
            //printHashMap(u32, *Entity_Type, &self.entities);

            self.entityUpdate(entity, EntityUpdateType.ADDED);
            std.debug.print("Added component {p} to Entitiy {d}\n", .{component, entity});
        }

        // Removes a component from a specified entitiy
        pub fn removeComponent(self: *Self, comptime component: anytype) void {
            
            // Remove component from reverse map
            const pointee_type = getComponentTypeFromComponent(component);
            var rev_component_map = self.getComponentMapPointerFromName("rev_"++getComponentMapNameFromType(pointee_type));

            //printHashMap(*const pointee_type, u32, component_map);
            const entity = rev_component_map.get(component) orelse std.debug.panic("The component {p} is not registered\n", .{component}); 
            if (!rev_component_map.remove(component)) {
                std.debug.panic("Entitiy {d} not associated with component {p} in reverse map\n", .{entity, component});
            }

            // Remove component from forwards map            
            var component_map = self.getComponentMapPointerFromName(getComponentMapNameFromType(pointee_type));
            if (!component_map.remove(entity)) {
                std.debug.panic("Entitiy {d} not associated with component {p} in forwards map\n", .{entity, component});
            }

            // Remove component flag from entity
            const index = self.component_index_map.get(getComponentMapNameFromType(pointee_type)) orelse std.debug.panic("No entry in component_index_map for {s}\n", .{@typeName(pointee_type)});
            var e = self.entities.get(entity) orelse std.debug.panic("No entity with ID {d} exists\n", .{entity});
            e.removeComponent(index, component);
           
            self.entityUpdate(entity, EntityUpdateType.COMP_REMOVED);
            std.debug.print("Removed component {p} from Entity {d}\n", .{component, entity});
        }

        // Trigger update systems
        pub fn preUpdate(self: *Self) void {
            for (self.systems_pre) |sys| {
                sys.callback(0.0, &sys.linked_entities);
            }
        }
        pub fn update(self: *Self) void {
            for (self.systems) |sys| {
                sys.callback(0.0, &sys.linked_entities);
            }
        }
        pub fn postUpdate(self: *Self) void {
            for (self.systems_post) |sys| {
                sys.callback(0.0, &sys.linked_entities);
            }
        }
    };
}

pub fn initComponentStruct(comptime ECS_Component_Struct_Type: type, comptime Components: []const type, allocator: std.mem.Allocator) ECS_Component_Struct_Type {
    var comp_struct: ECS_Component_Struct_Type = undefined;
    inline for (Components) |comp| {
        @field(comp_struct, "component_"++@typeName(comp)) = std.AutoHashMap(u32, *const comp).init(allocator);
    }
    inline for (Components) |comp| {
        @field(comp_struct, "rev_component_"++@typeName(comp)) = std.AutoHashMap(*const comp, u32).init(allocator);
    }

    return comp_struct;
}

